export const liveryDesigns = [...sportDescriptions, ...proDescriptions].map(
  (description, index) => {
    const theme = themes[index % 20],
      edition = index < 20 ? 'Sport' : 'Pro',
      [primary, secondary] = palettes[index % 20];
    return {
      variant: index + 1,
      theme,
      edition,
      name: `Винил ${theme} ${edition}`,
      description,
      primary,
      secondary,
      accent: '#fff6e5',
      ink: '#14233b',
    };
  },
);

export type LiveryDesign = (typeof liveryDesigns)[number];
